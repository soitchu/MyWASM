// Generates the parts of the native compiler that are data taken from the
// TS compiler, so the two stay in sync:
//   CoreWat.mypl  - the core WAT functions (getWASMCoreFunctions)
//   Builtins.mypl - the built-in function signatures in SemanticChecker
//
// Usage: bun Compiler-WASM/generate.ts
// tests/NativeChecker/generated.test.ts fails when these are out of date.

import { writeFileSync } from "node:fs";
import path from "node:path";
import { SemanticChecker } from "../Compiler/SemanticChecker";
import * as ast from "../Compiler/types";
import * as WASM from "../Compiler/WasmHelper";

const HEADER = "// Generated by Compiler-WASM/generate.ts. Do not edit.\n";

// MyPL string literals can't contain double quotes, so they're pushed as
// character code 34 between the pieces of the line
function appendLine(line: string) {
  const pieces = line.split('"');
  const statements: string[] = [];

  pieces.forEach((piece, i) => {
    if (i > 0) {
      statements.push("  text_push(t, 34);");
    }

    if (piece !== "") {
      statements.push(`  text_append_string(t, "${piece}");`);
    }
  });

  return statements;
}

function textFunction(name: string, text: string) {
  const lines = text.split("\n");
  const statements: string[] = [];

  lines.forEach((line, i) => {
    statements.push(...appendLine(line));

    if (i < lines.length - 1) {
      statements.push("  text_push(t, 10);");
    }
  });

  return `function void ${name}(Text t) {\n${statements.join("\n")}\n}\n`;
}

export function generateCoreWat() {
  return (
    HEADER +
    "// Appends the core WAT functions, with or without array checks\n\n" +
    "function void append_core_wat(Text t, bool unsafe_array) {\n" +
    "  if (unsafe_array) {\n" +
    "    append_core_wat_unsafe(t);\n" +
    "  } else {\n" +
    "    append_core_wat_safe(t);\n" +
    "  }\n" +
    "}\n\n" +
    textFunction("append_core_wat_safe", WASM.getWASMCoreFunctions(false)) +
    "\n" +
    textFunction("append_core_wat_unsafe", WASM.getWASMCoreFunctions(true))
  );
}

// Names of the DATA_TYPES singletons in Checker.mypl
function dataTypeName(dataType: ast.DataType) {
  for (const [name, value] of Object.entries(WASM.DATA_TYPES)) {
    if (value === dataType) {
      return `DT_${name.toUpperCase()}`;
    }
  }

  throw new Error(`Built-in uses a type that isn't in DATA_TYPES: ${dataType.type_name.lexeme}`);
}

export function generateBuiltins() {
  const checker = new SemanticChecker();
  const lines: string[] = [];

  lines.push("// Adds the built-in functions to the checker, in the same order as the");
  lines.push("// TS SemanticChecker, since that order decides the order of functions in");
  lines.push("// the output");
  lines.push("function void register_builtins(Checker c) {");
  lines.push("  VarDefList params = null;");

  for (const [key, funDef] of Object.entries(checker.functions)) {
    lines.push("");
    lines.push("  params = var_def_list_new();");

    for (const param of funDef.params) {
      lines.push(`  builtin_param(params, ${dataTypeName(param.data_type)}, "${param.var_name.lexeme}");`);
    }

    lines.push(
      `  map_set_fun(c.functions, text_from_string("${key}"), ` +
        `builtin_fun_def(${dataTypeName(funDef.return_type)}, "${funDef.fun_name.lexeme}", params));`
    );
  }

  lines.push("}");
  lines.push("");
  lines.push("// The types a built-in accepts for its first argument, or null when it");
  lines.push("// isn't overloaded. Only first arguments are overloaded");
  lines.push("function DataTypeList overloaded_types(Text fun_name) {");
  lines.push("  DataTypeList types = null;");

  for (const [name, byIndex] of Object.entries(checker.overloaded_functions)) {
    const indexes = Object.keys(byIndex);

    if (indexes.length !== 1 || indexes[0] !== "0") {
      throw new Error(`Only first arguments can be overloaded, but ${name} overloads ${indexes}`);
    }

    lines.push("");
    lines.push(`  if (text_equals_string(fun_name, "${name}")) {`);
    lines.push("    types = data_type_list_new();");

    for (const dataType of (byIndex as Record<string, ast.DataType[]>)["0"]) {
      lines.push(`    data_type_list_push(types, ${dataTypeName(dataType)});`);
    }

    lines.push("  }");
  }

  lines.push("");
  lines.push("  return types;");
  lines.push("}");

  return HEADER + "\n" + lines.join("\n") + "\n";
}

export const GENERATED_FILES: Record<string, () => string> = {
  "CoreWat.mypl": generateCoreWat,
  "Builtins.mypl": generateBuiltins,
};

if (import.meta.main) {
  for (const [file, generate] of Object.entries(GENERATED_FILES)) {
    writeFileSync(path.join(__dirname, file), generate());
  }
}
